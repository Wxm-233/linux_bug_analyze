def wsl_path(path):
    path = path.resolve().as_posix()
    if not re.match(r"^[A-Za-z]:/", path):
        raise ValueError("Expected Windows drive path")
    return "/mnt/" + path[0].lower() + path[2:]


def main():
    result_path = HERE / "probe_results.json"
    recovery = None
    if result_path.exists():
        previous_bytes = result_path.read_bytes()
        previous = json.loads(previous_bytes)
        expected_warning = "comparison of integer expressions of different signedness"
        error_lines = [line for line in previous.get("compile", {}).get("stderr", "").splitlines()
                       if "error:" in line]
        if not (sys.argv[1:] == ["--resume-after-sign-warning"]
                and previous.get("status") == "compile_failed_no_execution"
                and previous.get("execution_count") == 0
                and len(error_lines) == 2
                and all(expected_warning in line for line in error_lines)):
            raise SystemExit("Prior receipt exists; no repeated execution or arbitrary compile retry")
        initial = HERE / "probe_compile_initial.json"
        if initial.exists():
            raise SystemExit("The explicit compile-warning recovery was already used")
        initial.write_bytes(previous_bytes)
        recovery = {
            "initial_receipt": initial.name,
            "initial_receipt_sha256": sha(previous_bytes),
            "reason": "Original kernel signed/unsigned comparisons failed under harness-only -Werror.",
            "change": "Remove -Werror only; extracted original functions and logical inputs unchanged.",
            "previous_generated_source_sha256": previous["generated_source_sha256"],
            "previous_execution_count": 0,
        }
    packet_bytes = PACKET.read_bytes()
    packet = json.loads(packet_bytes)
    if packet["revision"] != REVISION:
        raise ValueError("Unexpected source revision")
    docs = {d["id"]: d for d in packet["original_source_request"]["documents"]}
    docs.update({d["id"]: d for d in packet["supplemental_documents"]})
    extracted = []
    for doc_id, function in (("X_lock_functions", "sched_core_lock"),
                             ("X_lock_functions", "sched_core_unlock"),
                             ("S_core", "sched_core_cpu_starting")):
        text, provenance = extract_function(docs[doc_id], function)
        extracted.append((text, provenance))
    sections = [PREAMBLE]
    for text, provenance in extracted:
        sections.append('\n#line %d "%s"\n%s' %
                        (provenance["start_line"], provenance["path"], text))
    sections.append(POSTAMBLE)
    source_bytes = "\n".join(sections).encode("utf-8")
    if recovery and sha(source_bytes) != recovery["previous_generated_source_sha256"]:
        raise ValueError("Warning recovery must not change the generated source")
    source = HERE / "consumer_probe.c"
    source.write_bytes(source_bytes)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    binary = OUTPUT / "consumer_probe"
    compile_command = ["wsl.exe", "-d", "Ubuntu", "--", "cc", "-std=c11",
                       "-O0", "-Wall", "-Wextra"]
    if not recovery:
        compile_command.append("-Werror")
    compile_command.extend([
                       wsl_path(source), "-o", wsl_path(binary)]
    )
    result = {
        "schema": "unchanged_consumer_mock_counterexample_v1",
        "date": "2026-10-15",
        "status": "prepared_not_run",
        "source_revision": REVISION,
        "source_packet": str(PACKET.relative_to(PROJECT)),
        "source_packet_sha256": sha(packet_bytes),
        "functions": [p for _, p in extracted],
        "generated_source": str(source.relative_to(PROJECT)),
        "generated_source_sha256": sha(source_bytes),
        "binary": str(binary.relative_to(PROJECT)),
        "scope": "Five constructed logical states in mock user-space C; not real kernel locks, hardware, reachability or concurrency validation.",
        "mock_contract": {
            "NR_CPUS": 4,
            "target_cpu": 1,
            "mask_stable_within_each_call": True,
            "rq_initialization": "All rq core pointers initially self except rq0->rq2 in missing-leader case.",
            "lock_calls": "Record actual calls from unchanged functions; no real synchronization.",
            "irq": "No-op mock; no interrupts or other CPUs are simulated.",
            "warnings": "Report original #line site; WARN_ON_ONCE state resets before every case.",
        },
        "compile": {"command": compile_command},
        "execution_count": 0,
        "new_kernel_runs": 0,
        "new_cases": 0,
    }
    if recovery:
        result["compile_warning_recovery"] = recovery
    result["compile_attempts_total"] = 2 if recovery else 1
    # Durable receipt before the one compilation/execution; never retry to pass.
    result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    compiled = subprocess.run(compile_command, capture_output=True, timeout=60)
    result["compile"].update({
        "returncode": compiled.returncode,
        "stdout": compiled.stdout.decode("utf-8", errors="replace"),
        "stderr": compiled.stderr.decode("utf-8", errors="replace"),
    })
    if compiled.returncode:
        result["status"] = "compile_failed_no_execution"
    else:
        result["binary_sha256"] = sha(binary.read_bytes())
        result["execution_count"] = 1
        result["status"] = "started_never_repeat"
        result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        command = ["wsl.exe", "-d", "Ubuntu", "--", wsl_path(binary)]
        executed = subprocess.run(command, capture_output=True, timeout=30)
        (HERE / "probe_stdout.json").write_bytes(executed.stdout)
        result["execution"] = {
            "command": command,
            "returncode": executed.returncode,
            "stdout_sha256": sha(executed.stdout),
            "stderr": executed.stderr.decode("utf-8", errors="replace"),
        }
        if executed.returncode:
            result["status"] = "execution_failed"
        else:
            output = json.loads(executed.stdout)
            result["cases"] = output["cases"]
            result["status"] = "completed_mock_user_space_only"
    result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": result["status"], "execution_count": result["execution_count"],
                      "case_rows": len(result.get("cases", [])), "receipt": str(result_path)}))
    if result["status"] != "completed_mock_user_space_only":
        sys.exit(1)


if __name__ == "__main__":
    main()
